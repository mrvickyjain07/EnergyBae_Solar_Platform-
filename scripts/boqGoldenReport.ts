// scripts/boqGoldenReport.ts
// Run with: npx tsx scripts/boqGoldenReport.ts
//
// Regenerates, from the committed workbook fixtures:
//   - src/modules/boqEngine/fixtures/expected-comparison.json  (pinned by workbookGolden.test.ts)
//   - docs/phase5/boq-golden-report.md                         (the MATCH / DIFFERENT report)
// Re-run after an intentional engine or fixture change, review the diff of
// both files, and commit them together.
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";
import { LEGACY_V1 } from "../src/modules/boqEngine/legacyV1";
import { formatExpr } from "../src/modules/boqEngine/ruleEngine";
import { CLASS_LABEL, compareFixture, workbookFindings, type Fixture } from "../src/modules/boqEngine/workbookGolden";

const DIR = "src/modules/boqEngine/fixtures/workbooks";
const files = readdirSync(DIR).filter((f) => f.endsWith(".json")).sort();
const fixtures = files.map((f) => ({ file: f, fx: JSON.parse(readFileSync(join(DIR, f), "utf8")) as Fixture }));

const fmt = (x: number | null | undefined) => (x === null || x === undefined ? "—" : `${+x.toFixed(4)}`);
const esc = (s: string) => s.replace(/\|/g, "/").replace(/\n/g, " ");
const cellStr = (c?: { f?: string; v: unknown }) => (!c ? "—" : c.f ? `\`${esc(c.f)}\` → ${typeof c.v === "number" ? fmt(c.v) : esc(String(c.v))}` : `typed ${typeof c.v === "number" ? fmt(c.v) : esc(String(c.v))}`);

const expected: Record<string, unknown> = {};
const out: string[] = [];
const P = (...l: string[]) => out.push(...l);

const results = fixtures.map(({ file, fx }) => ({ file, fx, cmp: compareFixture(fx), findings: workbookFindings(fx) }));
for (const r of results) {
  expected[r.file] = r.cmp.lines.map((l) => ({ key: l.key, result: l.result, workbookQty: l.workbookQty, calcQty: l.calcQty }));
}

P("# Phase 5B — Workbook golden report (legacy-v1 vs the 14 BOQ sheets)", "",
  "> Generated by `scripts/boqGoldenReport.ts` from the committed fixtures in `src/modules/boqEngine/fixtures/workbooks/` (extracted from the six source workbooks by `scripts/extractBoqFixtures.ts`). Do not edit by hand — re-run the script.", "",
  "**Labels.**",
  "- **[CODE]**: current calcBOQ behaviour (= legacy-v1, proven identical by `legacyParity.test.ts`).",
  "- **[WB]**: workbook cell fact.",
  "- **[DEFECT]**: confirmed current calcBOQ defect.",
  "- **[BIZ]**: business decision, not taken here.",
  "- **[INF]**: assumption or inference.",
  "",
  "**What this report does not do.** It does not choose between conflicting workbook rules. It implements none of: F/B/SH/Prestructure, earthing, commercial, kW-basis, capacity-range or structure rules. It changes no quote.",
  "Quantities only: legacy-v1 is run with the default catalogue (BOS prices ₹0) [CODE], so prices are not comparable.", "");

P("## 1. Summary", "", "| Workbook / sheet | MATCH | DIFFERENT | MISSING IN calcBOQ | NOT IN WORKBOOK | Workbook findings |", "|---|---|---|---|---|---|");
for (const r of results) {
  const c = (x: string) => r.cmp.lines.filter((l) => l.result === x).length;
  P(`| ${r.fx.source.workbook} / \`${r.fx.source.sheet}\` | ${c("MATCH")} | ${c("DIFFERENT")} | ${c("MISSING IN calcBOQ")} | ${c("NOT IN WORKBOOK")} | ${r.findings.length} |`);
}
P("", "No sheet is fully reproduced by legacy-v1. Every MATCH below is an exact equality from an actual run (tolerance 1e-9).", "");

P("## 2. Current calcBOQ behaviour (legacy-v1) [CODE]", "",
  "Rendered directly from `src/modules/boqEngine/legacyV1.ts`, which `legacyParity.test.ts` proves equal to `calcBOQ()` across 4,000 randomized inputs plus the 14 workbook input sets. `calcBOQ()` itself is unchanged.",
  "",
  "Notation:",
  "- `num(x)`: blank → 0.",
  "- `int(x)`: truncated.",
  "- Every line's qty can be overridden by key `sr`, its cost by `c<sr>`, and the line removed by `x<sr>`.",
  "- `sanitizePrice` applies to all of them.",
  "", "**Quantities**", "", "| Name | Expression |", "|---|---|");
for (const q of LEGACY_V1.quantities) P(`| ${q.key} | \`${esc(formatExpr(q.expr))}\` |`);
P("", "**Lines**", "", "| sr | Group | Unit | Qty | Unit cost |", "|---|---|---|---|---|");
for (const it of LEGACY_V1.items) P(`| ${it.sr} ${esc(formatExpr(it.name).replace(/"/g, ""))} | ${it.group} | ${it.unit} | \`${esc(formatExpr(it.qty))}\` | \`${esc(formatExpr(it.unitCost))}\` |`);
P("", `Custom catalogue items are appended from sr ${LEGACY_V1.customCatalogueItems!.startSr} (qty 0 unless overridden, cost = item price).`, "");

P("## 3. Legacy Calculator Defects [DEFECT]", "",
  "Confirmed by code reading and by running legacy-v1 on the workbook inputs. **All three were fixed in calcBOQ (and legacy-v1) on 2026-10-05 with business approval**, together with editable cable spares. The tables below show the workbook against the fixed calculator, with structure legs and spares mapped from the workbook (§7); the [CODE] bullets describe the formula before the fix.", "");
const D = (key: string) => results.map((r) => ({ r, l: r.cmp.lines.find((x) => x.key === key)! }));
P("### D1. Anchor bolts (sr 22) — FIXED 2026-10-05", "",
  "- [CODE] before fix: `qty = J46 × 4`, `J46 = R53 × 2`, `R53 = ceil(S53 ÷ 6) × 6`, `S53 = B26×0.75 + B28 + B29`. The rounded structure length (metres) is used as if it were the leg count.",
  "- [WB] Ashwini 3 kW:",
  "  - anchor bolts `=J46*4`;",
  "  - base plates J46 `=R53*2`;",
  "  - R53 `=sum(R49:R52)` = the leg count (4);",
  "  - the structure length is a different cell (`J44 =roundup(S53/6,0)*6`).",
  "- [WB] The parameter cells B26 / B28 / B29 that calcBOQ used are referenced by no workbook formula.",
  "- Fix: a typed \"Structure Legs\" input; anchor bolts = legs × 2 base plates × 4.",
  "", "| Sheet | Workbook qty (formula) | calcBOQ qty | × |", "|---|---|---|---|");
for (const { r, l } of D("22")) P(`| ${r.fx.source.sheet} | ${fmt(l.workbookQty)} (${l.rows.map((x) => x.formula ?? "typed").join("; ")}) | ${fmt(l.calcQty)} | ${l.workbookQty ? fmt((l.calcQty ?? 0) / l.workbookQty) : l.calcQty ? "∞ (workbook 0)" : "1"} |`);
P("", "### D2. 4 mm² lugs (sr 20) and cable tags (sr 29) — FIXED 2026-10-05", "",
  "- [CODE] before fix: `B35 = B46 < 32 ? 1 : 2`; lugs = `B35×2 + B37×2`; tags = `B37 + B35×2 + 2`.",
  "- [WB] Every sheet:",
  "  - **B35 = \"DC Cable Size (No. of Cores)\", typed 2**;",
  "  - calcBOQ's B35 formula is the workbook's \"No. of DC MCB\" cell (`=IF(B46<B42,1,2)`, B42 = 32);",
  "  - lugs J33 `=(B35*2)+(B37*2)` and tags J42 `=(B37+B35*2)+2` reference the cores cell.",
  "", "| Sheet | Lugs WB / calcBOQ | Tags WB / calcBOQ |", "|---|---|---|");
const lugs = D("20"), tags = D("29");
lugs.forEach(({ r, l }, i) => P(`| ${r.fx.source.sheet} | ${fmt(l.workbookQty)} / ${fmt(l.calcQty)} | ${fmt(tags[i].l.workbookQty)} / ${fmt(tags[i].l.calcQty)} |`));
P("", "### D3. DC cable length (sr 8) — FIXED 2026-10-05", "",
  "- [CODE] before fix: `B16 = ceil(B23×1.2 + B9×2.3) × B7` (× **inverters**); qty = `B16 + 15`.",
  "- [WB] B16 `=ROUNDUP(($B$23*1.2)+($B$9*2.3),0)*B32` (× **strings**). Aaryan sheets use no multiplier. qty = `B16 + C16` (typed spare).",
  "- The table separates the multiplier effect from the spare effect: \"calcBOQ length\" = calcBOQ qty − spare (the workbook C16, or 15 when blank).",
  "", "| Sheet | Inverters | Strings | WB length B16 (formula) | calcBOQ length | WB spare C16 | WB qty | calcBOQ qty |", "|---|---|---|---|---|---|---|---|");
for (const { r, l } of D("8")) {
  const p = r.fx.params["DC Cable Length (MTS.)"];
  P(`| ${r.fx.source.sheet} | ${r.fx.params["No. of Inverter"]?.B?.v} | ${r.fx.params["No. of Strings"]?.B?.v} | ${cellStr(p?.B)} | ${fmt((l.calcQty ?? 0) - (typeof p?.C?.v === "number" ? p.C.v : 15))} | ${p?.C?.v ?? "—"} | ${fmt(l.workbookQty)} | ${fmt(l.calcQty)} |`);
}
P("", "[INF] D1–D3 look like porting slips: calcBOQ reuses the workbook cell names (B35, R53, J46) for different formulas.", "");

P("## 4. Workbook internal findings [WB]", "", "Facts about the workbooks themselves, not judgements of which value is correct.", "", "| Sheet | Row | Finding |", "|---|---|---|");
for (const r of results) for (const f of r.findings) P(`| ${r.fx.source.sheet} | ${f.row} | ${esc(f.issue)} |`);
P("");

P("## 5. Workbook behaviour and line-by-line comparison", "",
  "Per sheet:",
  "- the workbook inputs as read from the cells [WB];",
  "- the engine inputs derived from them [INF, §7];",
  "- every line.",
  "",
  "A workbook line's qty is the sum of all its rows (each row and formula is listed).",
  "",
  "Classes:",
  ...Object.values(CLASS_LABEL).map((x) => `- ${x}`),
  "");
const INPUT_LABELS = ["Required Solar Capacity", "Panel Price/Wp", "Solar Module Size (W)", "System Connection Phase", "Building No. of Floors", "Inverter Installation Floor", "No. of Inverter", "Inverter Size", "No. of Panel Rows", "Structure Height Lower (FT.)", "Structure Height Upper (FT.)", "Battery Size", "No. of Batteries", "No. of Earthing Pit", "No. of Solar Panels", "No. of Strings", "DC Cable Length (MTS.)", "AC Cable Length (MTS.)", "Earthing Cable Length for Structure (MTS.)", "Earthing Cable Length for Inverter (MTS.)", "LA Earthing Cable Length (MTS.)", "DC Cable Size (sqmm)", "AC Cable Size (sqmm)"];
for (const r of results) {
  const { fx, cmp } = r;
  P(`### ${fx.source.workbook} / \`${fx.source.sheet}\``, "", "| Workbook input | Row | B | C |", "|---|---|---|---|");
  for (const lab of INPUT_LABELS) { const p = fx.params[lab]; if (p) P(`| ${lab} | ${p.row} | ${cellStr(p.B)} | ${p.C ? cellStr(p.C) : ""} |`); }
  P("", `Engine inputs [INF]: \`${esc(JSON.stringify(cmp.inputs))}\``, "",
    "| sr | Line | Workbook rows (formula → qty) | WB qty | legacy-v1 qty | Diff | Result | Class | Reason |", "|---|---|---|---|---|---|---|---|---|");
  for (const l of cmp.lines) {
    const rows = l.rows.map((x) => `r${x.row} ${x.formula ? "`" + esc(x.formula) + "`" : "typed"} → ${fmt(x.qty)}`).join("; ") || "—";
    P(`| ${/^\d+$/.test(l.key) ? l.key : "—"} | ${esc(l.label)} | ${rows} | ${fmt(l.workbookQty)} | ${fmt(l.calcQty)} | ${l.diff === null ? "—" : (l.diff >= 0 ? "+" : "") + fmt(l.diff)} | ${l.result} | ${l.cls ? CLASS_LABEL[l.cls] : "—"} | ${esc(l.why) || "—"} |`);
  }
  P("");
}

